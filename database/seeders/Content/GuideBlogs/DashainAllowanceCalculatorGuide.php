<h2>What is Dashain allowance?</h2>

<p>Dashain allowance is a periodic cash benefit paid around the Dashain–Tihar season so employees can meet extra festival expenses. It is distinct from regular monthly salary, overtime, and annual performance bonuses—though casual language sometimes lumps them together. In many private-sector firms the allowance equals one month's <em>basic salary</em>. Public-sector and banking schedules may publish fixed amounts by grade. Start-ups sometimes pay a flat NPR figure for all staff regardless of seniority.</p>

<p>The payment timing usually falls in Ashwin/Kartik (September–October in the Gregorian calendar), aligned with payroll cycles. Some organisations split advance and balance; others pay a single tranche before employees leave for home districts.</p>

<h2>Legal and policy context</h2>

<p>Nepal's labour framework recognises festival-related benefits in various industries through CBAs and employer policies. The precise entitlement for your workplace is defined by:</p>

<ul>
<li>Your individual employment contract or appointment letter</li>
<li>The employer's HR handbook or festival bonus circular</li>
<li>Applicable collective bargaining agreement if you are union-covered</li>
<li>Industry norms (banks and INGOs often differ from informal sector wages)</li>
</ul>

<p>There is no single national formula mandating "exactly one month gross" for every private employee in every sector—though one month basic is the dominant convention in formal employment. When in doubt, ask HR for the written rule rather than relying on colleague anecdotes from a different department.</p>

<h2>Common calculation approaches</h2>

<h3>Fixed amount by grade</h3>

<p>Large organisations publish a table: Grade 7 receives NPR X, Grade 8 receives NPR Y, and so on. The allowance does not float with current basic if the table is absolute—unless the circular says "one month basic, minimum NPR X."</p>

<h3>Salary-linked: months of basic</h3>

<p><strong>Allowance = Basic salary × Number of months</strong></p>

<p>One month (1.0) is standard. Some generous policies offer 1.5 months for certain grades; contractual roles may specify 0.5 months if employment started mid-year and pro-rating applies.</p>

<h3>Percentage of basic</h3>

<p><strong>Allowance = Basic × (Percent ÷ 100)</strong></p>

<p>Functionally similar to fractional months—100% of basic equals one month.</p>

<h3>Pro-rating for partial service year</h3>

<p>If policy allows, employees who joined after the fiscal or calendar cut-off receive a reduced allowance:</p>

<p><strong>Pro-rated allowance = Full allowance × (Eligible months worked ÷ 12)</strong></p>

<p>Not every employer pro-rates; some pay full festival bonus after a minimum tenure (e.g., six months). Read the circular.</p>

<h2>Which salary components count as "basic"?</h2>

<p>Misunderstanding the base causes the largest gap between expectation and payslip.</p>

<ul>
<li><strong>Usually included:</strong> contracted basic pay (the core line on your salary slip)</li>
<li><strong>Usually excluded unless policy says otherwise:</strong> overtime, travel allowance, fuel, mobile, housing, and performance incentives</li>
<li><strong>Debate zone:</strong> dearness allowance or grade allowance—some CBAs fold these into festival base; others do not</li>
</ul>

<p>Gross salary and basic salary are not interchangeable. If your gross is NPR 55,000 but basic is NPR 30,000, a "one month basic" festival payment is NPR 30,000—not 55,000.</p>

<h2>Worked example: one month basic</h2>

<p>An employee earns NPR 42,000 basic monthly. Policy grants one month's basic as Dashain allowance.</p>

<ol>
<li>Allowance = 42,000 × 1 = NPR 42,000</li>
</ol>

<p>If the same employee receives NPR 18,000 in allowances monthly, festival bonus still tracks basic unless HR policy explicitly widens the base.</p>

<h2>Worked example: half month for mid-year joiner</h2>

<p>Policy: one month basic, pro-rated for staff with fewer than six months' service by 1 Shrawan, at 50% of full entitlement. Basic = NPR 36,000.</p>

<ol>
<li>Full entitlement would be NPR 36,000</li>
<li>Pro-rated at 50% = NPR 18,000</li>
