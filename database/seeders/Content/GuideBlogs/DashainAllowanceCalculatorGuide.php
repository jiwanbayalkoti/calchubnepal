<p>Dashain is Nepal's longest and most widely celebrated festival, and for millions of employees it also marks the arrival of a festival allowance—often called Dashain bonus or festival bonus. HR departments start spreadsheets weeks before Ghatasthapana; family budgets depend on that lump sum for travel, new clothes, gifts, and feast expenses. Yet the "one month basic" rule of thumb is not universal: banks, NGOs, factories, and government bodies each follow policies shaped by the Labour Act, collective bargaining agreements (CBAs), and internal grade tables.</p>

