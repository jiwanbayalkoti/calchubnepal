<ul>
<li>Publish the rule once in writing before calculation season—reduces rumor and favoritism claims.</li>
<li>Apply the same base definition (basic vs gross) across departments.</li>
<li>Document exceptions (retiring staff, suspended employees, probationers) in the same circular.</li>
<li>Show the arithmetic on payslips or festival payment advice notes.</li>
