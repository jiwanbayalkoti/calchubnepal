<p>Employers commonly treat festival bonus up to one month's basic salary as tax-exempt or separately accounted under income-tax practice, while amounts above that threshold may be added to taxable income for the year. IRD rules and Finance Act provisions evolve; payroll teams issue internal memos each fiscal year.</p>

