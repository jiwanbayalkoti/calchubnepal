<h2>Frequently asked questions</h2>

<h3>Is Dashain allowance mandatory for all jobs?</h3>
<p>Entitlement depends on contract, law applicable to your establishment, and CBA—not on festival culture alone. Informal daily-wage work may not include it.</p>

<h3>How many months of salary is typical?</h3>
<p>One month basic is the most common formal-sector convention; verify your own policy.</p>

<h3>Do interns and probationers get festival bonus?</h3>
<p>Only if policy explicitly includes them—many employers exclude or pro-rate probationers.</p>

<h3>Is festival allowance the same as the 13th month salary?</h3>
<p>Colloquially people conflate them; legally and payroll-wise they may be separate line items. Read definitions in your handbook.</p>

<h3>Can my employer pay goods instead of cash?</h3>
<p>Some factories historically paid rice or goods; modern formal payroll usually pays cash. Contract terms govern.</p>

